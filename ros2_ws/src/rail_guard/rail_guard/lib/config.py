@dataclass
class TrackerConfig:
    max_assoc_distance: float = 2.0  # ворота ассоциации, м
    # Прирост ворот с дальностью. На 100 м центроид кластера гуляет на метры
    # из-за смены видимых граней, а ось коридора — ещё на метр: при прежних
    # 0.02 (4 м на сотне) трек рвался и пересоздавался с новым номером,

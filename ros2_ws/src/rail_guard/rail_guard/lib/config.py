"""Параметры пайплайна детекции. Одна dataclass — один этап обработки.

Параметры делятся на три класса, и это деление — главное, что здесь есть.

**Физика носителя и линии.** Габарит подвижного состава, колея, длина
вагона, замедления, время реакции. Их нельзя вывести из облака точек: они
заданы регламентом и известны заранее. Это и есть содержимое профиля
(`config/metro.yaml`, `config/mainline.yaml`) — всё, что требуется задать,
чтобы система поехала на новой линии.

**Измеряемое по данным.** Ориентация датчика, плотность его лучей,
дальнобойность, тип сцены (замкнутое сечение или открытый перегон), ширина
тоннеля, запас реального времени. Всё это определяется по самим кадрам
(`lib/frames.py`, `lib/sensor_model.py`, `lib/scene.py`) и в профиле имеет
значение `None` — «измерить». Задать число вручную можно, но это осознанное
подавление автоматики, а не норма.

**Выводимое из первых двух.** Пороги числа точек, радиус связности
кластеризации, длина экстраполяции коридора, полосы модели свободного
пространства. Они не подбираются, а считаются формулами в `lib/derive.py` из
габарита носителя и измеренных свойств датчика и сцены.

Значение `None` в поле означает «определяется автоматически»; в YAML ему
соответствует `auto` или `null`. Все длины в метрах, углы в радианах.
"""
from dataclasses import dataclass, field, asdict
from typing import Any, Dict, Optional, Tuple


@dataclass
class SensorConfig:
    # Положение лидара относительно base_link (нос поезда, УГР). Нужно только
    # если облако приходит в собственной СК лидара и не преобразовано через TF.
    mount_height: float = 2.0
    # Углового разрешения и дальнобойности здесь нет намеренно: они
    # измеряются по самим кадрам (lib/sensor_model.py). Числом в профиле они
    # означали бы, что система настроена на один комплект лидаров и молча
    # деградирует на другом — пороги детекции считаются как раз из них.
    min_range: float = 1.5
    # Ориентация датчика: какая его ось смотрит вперёд и какая вверх.
    # «auto» — определить по первому пригодному кадру (см. lib/frames.py),
    # иначе имя оси: x, -x, y, -y, z, -z. Весь алгоритм работает в REP-103
    # (X вперёд, Y влево, Z вверх), и облако приводится к ней до фильтрации:
    # в чужой СК предфильтр выбрасывает облако целиком, и система молча
    # рапортует «путь свободен».
    forward_axis: str = "auto"
    up_axis: str = "auto"
    auto_min_points: int = 2000        # меньше — ориентацию по кадру не понять
    auto_min_confidence: float = 0.25
    auto_max_attempts: int = 5         # затем считаем, что СК уже рабочая


@dataclass
class PreprocessConfig:
    # Обрезка рабочей области: смотрим только вперёд и в разумной полосе.
    # Границы по дальности и ширине — None («измерить»): дальность берётся из
    # наблюдаемой дальнобойности датчика, ширина — из габарита носителя с
    # запасом на уход оси в кривой (lib/derive.py). Числа в профиле означали
    # бы, что рабочая зона подогнана под конкретный лидар и участок.
    x_min: float = 2.0
    x_max: Optional[float] = None
    y_abs_max: Optional[float] = None
    # Рабочая зона по высоте задаётся в СК датчика, а полотно на сотне метров
    # уходит по уклону: при 3 % это 3 м, и прежняя граница -3 м срезала цель
    # вместе с путём ровно там, где борются за дальность.
    z_min: float = -7.0
    z_max: float = 9.0
    # Габарит самого поезда — точки внутри отбрасываются (отражения от носа).
    ego_box: Tuple[float, float, float, float, float, float] = (-5.0, 2.5, -2.0, 2.0, -3.0, 4.0)
    # Воксельная дискретизация по полосам дальности: дальние точки не прореживаем,
    # иначе теряется как раз то, ради чего борются за дальность.
    voxel_bands: Tuple[Tuple[float, float], ...] = ((30.0, 0.12), (60.0, 0.06), (1e9, 0.0))
    # Отсечка по интенсивности для дальних возвратов (пыль/капли/выхлоп).
    # 0 = выключено; включать только зная шкалу интенсивности конкретного лидара.
    min_intensity_far: float = 0.0
    intensity_far_range: float = 60.0
    # Потолок на размер входного облака. None — вырабатывать по факту: тракт
    # измеряет собственное время и период кадров и уступает плотность ближнего
    # поля ровно тогда, когда перестаёт укладываться в период лидара
    # (см. GaugeConfig.adaptive_range). Число здесь — это настройка под
    # конкретный процессор, а он на объекте другой; 0 — не ограничивать вовсе.
    max_input_points: Optional[int] = None
    # Прореживать только ближнее поле: дальние точки — это и есть дальность
    # обнаружения, их резать нельзя. У 128-луча 97 % точек кадра лежат ближе
    # 20 м, поэтому потолок плотности набирается почти целиком за счёт
    # ближней зоны, а дальняя доходит до детектора нетронутой.
    decimate_below: float = 15.0
    # Нижняя граница потолка плотности при нехватке времени, доля исходного
    # облака. Под нагрузкой система сначала уступает плотность ближнего поля
    # (там точек избыток) и только потом — дальность: дальние точки и есть то,
    # ради чего всё. Доля, а не число: у 64- и 128-луча размер кадра
    # различается втрое, и абсолютный порог означал бы разное для них.
    min_input_fraction: float = 0.25
    # Доля точек, ниже которой кадр считается вырожденным: облако пришло в
    # чужой СК, датчик закрыт или рабочая зона задана неверно.
    degenerate_fraction: float = 0.02


@dataclass
class GroundConfig:
    bin_size: float = 5.0            # длина продольной ячейки для оценки полотна
    # Полоса поиска полотна вокруг оси пути. None — из междупутья: в полосу
    # не должно попадать полотно соседнего пути, лежащее на другой высоте.
    search_half_width: Optional[float] = None
    low_percentile: float = 20.0     # перцентиль z, принимаемый за уровень балласта
    plane_tolerance: float = 0.12    # допуск при уточнении плоскости МНК
    max_slope: float = 0.05          # макс. правдоподобный продольный уклон (5 %)
    follow_tolerance: float = 0.45   # коридор слежения за поверхностью между ячейками
    min_bin_points: int = 20
    rail_head_offset: float = 0.25   # головка рельса над уровнем балласта


@dataclass
class TrackConfig:
    gauge: float = 1.59              # расстояние между ЦЕНТРАМИ головок рельсов:
                                     # колея + ширина головки (1520 + ~70 мм для РФ,
                                     # 1435 + ~70 мм = 1.505 для колеи 1435 мм)
    # Расстояние между осями смежных путей — норматив линии (метро 3.4-4.0 м,
    # магистральная железная дорога 4.1-4.5 м). Из него выводятся полосы
    # поиска: и рельсы, и полотно нужно искать в пределах своего пути, иначе
    # в полосу попадает соседний — а это ровно тот случай, когда коридор
    # уезжает на чужой путь и система тормозит по идущему рядом составу.
    spacing: float = 4.1
    rail_height_min: float = 0.10    # головка рельса над уровнем балласта
    rail_height_max: float = 0.32
    near_start: float = 4.0          # ближе поезд закрывает путь собственным носом
    max_fit_range: float = 120.0     # дальше сечение пути уже не разрешается
    # Полоса поиска вокруг опорной оси. None — вывести из междупутья: поиск
    # не должен дотягиваться до соседнего пути.
    search_half_width: Optional[float] = None
    min_rail_points: int = 200
    profile_bin: float = 4.0         # продольная ячейка профиля
    lat_bin: float = 0.05            # поперечная ячейка профиля
    center_weight: float = 0.6       # вес «провала» между рельсами в шаблоне
    outer_offset: float = 0.45       # где шаблон ожидает пустоту снаружи колеи
    outer_weight: float = 0.4
    rail_tolerance: float = 0.12     # допуск «точка легла на нитку», м
    min_bin_points: int = 6          # отражений на нитках, чтобы ячейка считалась подтверждённой
    max_bin_gap: int = 2             # сколько ячеек подряд можно не узнать
    min_fit_range: float = 15.0      # короче — считаем, что путь не распознан
    # Насколько тает зона доверия в кадре, где сечение пути не распознано.
    # Физически она сокращается ровно на пройденный путь: подтверждённое на
    # 44 м впереди после проезда полутора метров подтверждено на 42.5 м. Плюс
    # минимальная потеря за само неподтверждение — иначе на стоянке зона
    # висела бы вечно. Прежнее «минус 10 м за кадр» обнуляло ось за три-четыре
    # кадра, и коридор падал до 25 м в 3-23 % кадров записи.
    fallback_decay_min: float = 1.0
    min_radius: float = 150.0        # минимальный радиус кривой в сетке гипотез
    lin_span: float = 0.05           # диапазон поправки курса относительно опорной оси
    coarse_lin: int = 13             # сетка гипотез: курс
    coarse_quad: int = 41            # сетка гипотез: кривизна
    fine_steps: int = 9              # уточняющая сетка
    prior_weight: float = 0.0002     # штраф за отход от опорной оси
    max_axis_shift: float = 1.5      # насколько ось может уйти от опорной за кадр, м
    shift_check_range: float = 50.0  # на какой дальности проверяется это ограничение
    row_weight_range: float = 60.0   # дальность, на которой вес ячейки падает вдвое
    smoothing: float = 0.5           # доля новой оценки при межкадровом сглаживании
    confidence_decay: float = 120.0  # на сколько метров хватает экстраполяции дуги
    # Продление оси по обделке тоннеля (lib/track.py, estimate_tunnel_center).
    # Рельсы различимы на первых 30-40 м, а стены тоннеля видны на 80-110 м, и
    # путь лежит в трубе с постоянным смещением от её центра. Смещение
    # калибруется там, где рельсы видны, и дальше ось ведёт уже сам тоннель.
    # None — решать по сцене: ведение осью тоннеля включается там, где кадр
    # показывает замкнутое сечение (lib/scene.py), и само отключается на
    # открытом перегоне. Прежде это был переключатель в профиле, то есть
    # решение, принятое заранее и на всю запись, — а поезд метро выезжает на
    # открытый участок, магистральный въезжает в тоннель.
    guide_enabled: Optional[bool] = None
    # Продольная полоса, в которой мерится труба. None — вывести из
    # максимальной длины предмета: полоса должна быть длиннее его, иначе
    # предмет у стены подменяет собой стену.
    guide_band: Optional[float] = None
    guide_height_min: float = 0.6    # слой стен над УГР: выше полотна,
    guide_height_max: float = 2.4    # ниже свода и кабельных консолей
    guide_min_side_points: int = 8   # отражений на сторону в полосе: на 100 м
                                     # от обделки приходит 12-17 точек на полосу
    guide_quantile: float = 90.0     # перцентиль |смещения|, принимаемый за стену
    # Полоса поиска стен. None — от измеренной полуширины сечения (lib/scene.py):
    # абсолютный порог «шире восьми метров — не тоннель» пришлось бы
    # подбирать под конкретный тоннель.
    guide_max_half_width: Optional[float] = None
    guide_max_width_jump: float = 1.2   # отличие ширины полосы от ближней трубы
    guide_max_spread: float = 0.8    # разброс смещения в зоне рельсов, при котором
                                     # тоннелю ещё можно доверять ведение оси
    guide_confidence: float = 0.85   # уверенность в зоне, подтверждённой тоннелем
    guide_rail_weight: float = 3.0   # во сколько раз рельсы весомее стен при подгонке
    # Насколько подгонка по трубе вправе сдвинуть ось там, где её уже знают
    # рельсы. Больше — значит тоннель переписывает рельсы, а это ровно тот
    # случай, когда «своя» стена оказалась не своей.
    guide_max_near_error: float = 0.15
    # Насколько круто ось тоннеля вправе уходить вбок между соседними полосами
    # (доля длины полосы). None — считать из минимального радиуса кривой:
    # на дальности x дуга радиуса R имеет наклон x/R, и всё, что круче, —
    # потерянная труба, а не поворот пути. Фиксированное число здесь
    # означало бы предел, не связанный с геометрией линии.
    guide_max_slope: Optional[float] = None
    # Межкадровое сглаживание измеренной оси: доля новой оценки. Стена на
    # сотне метров даёт считанные отражения, и оценка центра там гуляет на
    # метр-полтора от кадра к кадру — коридор «дышит», а препятствие то
    # попадает в него, то нет. Ось предыдущего кадра сдвигается на пройденный
    # путь и смешивается с новой.
    guide_smoothing: float = 0.35
    # Уточнять ли саму дугу по трубе. По умолчанию нет: рельсы задают ось
    # точнее, а сдвиг ближней зоны даже на 10-15 см добавляет ложных тревог
    # у границы габарита. Труба служит подтверждением дальности, а не осью.
    guide_refits_axis: bool = False


@dataclass
class GaugeConfig:
    """Габарит поезда — та самая зона, вторжение в которую и ищем."""
    half_width: float = 1.45         # половина ширины подвижного состава
    lateral_margin: float = 0.25     # запас на раскачку/износ пути/ошибку оси
    height: float = 3.75             # верх габарита над УГР
    # Низ габарита над УГР — нижняя кромка подвижного состава. Предмет, не
    # достающий до неё, поезд проходит без контакта, а вот путевое
    # оборудование (шпалы, накладки, лотки, тяги) как раз лежит ниже, и
    # опущенная под УГР граница ловила именно его: доля экстренных на
    # `roundT_pressureGate_roundT` была 14 % против 7 % при физической границе.
    bottom: float = 0.05
    # Расширение габарита в кривой (вынос кузова). Приближение: dW = L^2/(8R).
    car_length: float = 19.2
    # Дальность коридора. None — из наблюдаемой дальнобойности датчика и
    # тормозного пути: строить коридор дальше, чем виден путь и чем нужно для
    # остановки, незачем, а число в профиле — это дальность того комплекта, на
    # котором мерили.
    max_range: Optional[float] = None
    step: float = 0.5                # шаг дискретизации оси коридора
    # За сколько метров от подтверждённой рельсами зоны ещё имеет смысл
    # строить коридор. Дальше идёт чистая экстраполяция дуги, и её ошибка
    # растёт как Δ²/2R: в тоннеле шириной 4.5 м ошибка оси в метр укладывает
    # коридор на обделку, а на открытом перегоне тот же метр ничего не
    # задевает. None — считать из минимального радиуса кривой и измеренного
    # зазора до боковой границы (lib/derive.py); 0 — не ограничивать.
    extrapolation_margin: Optional[float] = None
    # Дальность коридора подстраивается под то, успевает ли тракт за лидаром.
    # Смысл простой: система, которая считает кадр 150 мс при периоде 100,
    # видит далеко, но каждый третий кадр вовсе не смотрит — и препятствие,
    # появившееся в пропущенном кадре, обнаружится на 15 м ближе. Поэтому при
    # нехватке времени дальность уступается шагами, а когда запас появляется,
    # возвращается обратно.
    # Включено по умолчанию: производительность машины, на которой поедет
    # система, заранее неизвестна, и уступать плотность ближнего поля под
    # нагрузкой правильнее, чем копить задержку и терять кадры целиком.
    # Сначала уступается плотность (там точек избыток), и только когда
    # прореживать уже некуда — дальность.
    adaptive_range: bool = True
    # Нижняя граница дальности при любой нагрузке. None — тормозной путь при
    # эксплуатационной скорости: видеть ближе, чем можешь остановиться,
    # бессмысленно, и этот предел задаётся физикой поезда, а не процессором.
    adaptive_min_range: Optional[float] = None
    adaptive_step: float = 10.0
    adaptive_busy: float = 0.75        # доля периода, выше которой отступаем
    adaptive_idle: float = 0.60        # ниже которой возвращаем дальность


@dataclass
class AccumulationConfig:
    """Накопление кандидатов по кадрам для дальней зоны.

    Дальность обнаружения упирается не в алгоритм, а в число отражений: по
    измерению на записях метро человек на 60 м даёт 39 точек, на 100 м — 14,
    на 140 м — 7. Одного кадра там не хватает ни на кластер, ни на решение.
    Но препятствие неподвижно относительно тоннеля, а собственное перемещение
    поезда известно (оценка по облакам), поэтому кандидатов нескольких кадров
    можно свести в один момент времени: пять кадров дают на 100 м уже семьдесят
    точек вместо четырнадцати.

    Накапливаются только точки-кандидаты дальней зоны — их сотни, а не сотни
    тысяч, поэтому цена мала. Число точек объекта при этом делится на число
    сведённых кадров: пороги плотности остаются в прежней шкале.
    """
    enabled: bool = True
    frames: int = 5              # сколько кадров сводить (0 или 1 — выключено)
    min_range: float = 45.0      # ближе этой дальности накопление не нужно
    max_speed_error: float = 1.0  # м/с: выше — смаз больше размера цели
    max_dt: float = 1.0          # с: старше — не используем


@dataclass
class ClusterConfig:
    """Связность и порог плотности кластера.

    Оба параметра выводятся из измеренного углового шага решётки лучей и из
    размера минимальной значимой цели (SafetyConfig), а не подбираются:
    у редкого 16-лучевого лидара точки одной цели разнесены на метры там,
    где у плотного комплекта они лежат в сантиметрах, и единая настройка
    означает либо склейку всего подряд, либо рассыпание дальней цели.
    """
    # Базовый радиус связности: собственная неоднородность поверхности цели.
    # None — половина наименьшего размера минимальной цели: точки одного
    # предмета не могут быть разнесены дальше, чем он сам.
    eps0: Optional[float] = None
    # Прирост радиуса с дальностью. None — из углового шага решётки лучей:
    # соседние лучи на дальности r расходятся на r·Δφ, и связность обязана
    # это покрывать, иначе цель рассыпается на одиночные точки.
    eps_per_meter: Optional[float] = None
    eps_max: float = 1.5
    min_cluster_points: int = 3
    # Порог числа точек на опорной дальности. None — вывести из ожидаемого
    # числа отражений от минимальной цели (lib/derive.py). Дальше порог
    # масштабируется как 1/r², потому что так же падает число отражений.
    ref_range: float = 20.0
    ref_min_points: Optional[int] = None
    abs_min_points: int = 3
    # Потолок числа точек, который ставит само прореживание: после вокселя с
    # ребром L цель площадью A даёт не больше A/L² точек, сколько бы лучей в
    # неё ни попало. Требовать больше — значит не увидеть цель в ближней
    # зоне, где прореживание самое грубое. Полосы копируются из
    # PreprocessConfig, площадь — фронтальная площадь минимальной цели;
    # заполняет lib/derive.py.
    voxel_bands: Tuple[Tuple[float, float], ...] = ()
    target_area: float = 0.0
    detection_fraction: float = 0.1


@dataclass
class ObjectFilterConfig:
    # Точки самой поверхности полотна (балласт, шпалы, настил, «протёкшая»
    # оценка полотна) в кандидаты не идут: кластеризация связывает их в змею
    # вдоль пути, та склеивается со всем, что стоит рядом, и получается
    # «препятствие» длиной 20 м с уверенностью единица — а настоящий предмет
    # оказывается внутри этой змеи и отдельным объектом уже не виден.
    # Отсечка идёт от измеренной поверхности, а не от УГР: уровень головки
    # рельса над балластом — оценка, и ошибаться в ней ровно там, где решается
    # «предмет или полотно», нельзя.
    ground_band: float = 0.08
    # Собственная высота видимой части объекта. Вместе с низом габарита
    # (5 см над УГР) это означает: предметом считается то, что выступает над
    # уровнем головок рельсов на 13 см и выше — примерно 38 см над балластом.
    # Порог выведен из того, где поезд физически задевает предмет, а не
    # подобран по записям.
    min_size_z: float = 0.08
    min_top_height: float = -0.08    # верх объекта относительно УГР
    min_volume: float = 0.0015
    # Плоские протяжённые кластеры — это стрелка, кабельный лоток, край
    # платформы или «протёкшее» в коридор полотно, но не препятствие.
    flat_length: float = 3.0         # длина, с которой кластер уже «протяжённый»
    flat_height: float = 0.40        # и при этом низкий — путевое оборудование
    sheet_height: float = 1.00       # низкий, но широкий —
    sheet_width: float = 1.50        # это поверхность, а не предмет
    min_footprint: float = 0.05      # м^2; меньше — вырожденный кластер
    sliver_points: int = 15
    # Длина вдоль пути, с которой кластер перестаёт быть предметом. Опасный
    # предмет — человек, упавший груз, строительное оборудование — не бывает
    # длиннее нескольких метров; всё, что тянется на 8 м и больше, это
    # обделка, платформа, состав на соседнем пути или склейка нескольких
    # поверхностей. Порог физический, а не подобранный по записям.
    max_length: float = 8.0
    # Тонкая полоса, вытянутая вдоль пути: кабельный лоток, тяга, накладка,
    # лист обшивки, провод. Опасное препятствие такой формы не бывает —
    # человек в профиль даёт поперёк пути 0.3-0.4 м, упавший груз и техника
    # больше; всё, что тоньше 0.3 м и длиннее метра вдоль пути, лежит вдоль
    # него не случайно. Признак заменяет карту путевого оборудования, которой
    # на контрольной записи не будет.
    thin_max_width: float = 0.30     # поперёк пути
    thin_min_length: float = 1.00    # вдоль пути
    # Признаки инфраструктуры вдоль пути:
    wall_length: float = 3.0         # длинный вдоль пути и узкий поперёк
    wall_width: float = 0.7
    wall_edge_margin: float = 0.25   # и прижат к границе коридора
    overhead_clearance: float = 2.6  # низ выше этой высоты — портал, мост, свод тоннеля
    # Кластер, занимающий почти всю высоту габарита и стоящий на полотне, —
    # это стена в разрезе, портал или створка гермозатвора: препятствие от
    # головки рельса до свода в тоннеле не встречается (человек 1.8 м,
    # путевая техника до 2.5 м). Доля от высоты габарита, а не абсолютная
    # величина: профиль задаёт высоту вагона, и признак переносится на любую
    # линию вместе с ней.
    full_height_fraction: float = 0.85
    # Насколько кластер должен зайти внутрь свободного пространства тоннеля,
    # чтобы считаться предметом, а не его границей (обделка, кабельный лоток,
    # край платформы). None — из собственного шума измерения границы: сама
    # граница гуляет между полосами на величину порядка своей неровности, и
    # заход, не превышающий этого разброса, ничего не доказывает.
    # См. lib/tunnel.py; 0 — проверку не делать.
    min_intrusion: Optional[float] = None


# Минимум точек, при котором у кластера измеримы три габарита и можно
# говорить о его форме. Ниже — это всплеск, а не объект. Величина
# геометрическая, от датчика и линии не зависит, поэтому и живёт здесь одна
# на весь тракт: её же берёт решение как порог «по стольким точкам можно
# тормозить», пока он не выведен из измеренной плотности лучей.
GEOMETRIC_MIN_POINTS = 8



    # None — вывести из максимальной длины предмета.
    band: Optional[float] = None
    min_side_points: int = 12        # отражений на сторону в полосе
    # По скольким кадрам принимается решение о типе сцены. Переключать
    # механизмы тракта по одному кадру нельзя: у платформы и на стрелке
